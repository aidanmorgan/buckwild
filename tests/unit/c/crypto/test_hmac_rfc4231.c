/**
 * RFC 4231 Test Case 5 - Truncation Test
 * Key: 20 bytes of 0x0c
 * Data: "Test With Truncation"
 * Tests 128-bit (16-byte) truncated MAC
 */
void test_hmac_sha256_rfc4231_case5(void) {
    const uint8_t key[20] = {
        0x0c, 0x0c, 0x0c, 0x0c, 0x0c, 0x0c, 0x0c, 0x0c,
        0x0c, 0x0c, 0x0c, 0x0c, 0x0c, 0x0c, 0x0c, 0x0c,
        0x0c, 0x0c, 0x0c, 0x0c
    };
    const char *data = "Test With Truncation";
    // Full HMAC-SHA256 output
    const uint8_t expected_full[32] = {
        0xa3, 0xb6, 0x16, 0x74, 0x73, 0x10, 0x0e, 0xe0,
        0x6e, 0x0c, 0x79, 0x6c, 0x29, 0x55, 0x55, 0x2b,
        0xfa, 0x6f, 0x7c, 0x0a, 0x6a, 0x8a, 0xef, 0x8b,
        0x93, 0xf8, 0x60, 0xaa, 0xb0, 0xcd, 0x20, 0xc5
    };
    // Truncated to 128 bits (16 bytes)
    const uint8_t expected_truncated[16] = {
        0xa3, 0xb6, 0x16, 0x74, 0x73, 0x10, 0x0e, 0xe0,
        0x6e, 0x0c, 0x79, 0x6c, 0x29, 0x55, 0x55, 0x2b
    };
    uint8_t result[BUCKWILD_HMAC_SHA256_SIZE];

    int ret = buckwild_hmac_sha256(key, sizeof(key),
                                   (const uint8_t*)data, strlen(data),
                                   result);

    TEST_ASSERT_EQUAL_INT(0, ret);
    TEST_ASSERT_EQUAL_MEMORY(expected_full, result, 32);

    // Also verify truncated version matches (for adaptive HMAC policies)
    TEST_ASSERT_EQUAL_MEMORY(expected_truncated, result, 16);
}

